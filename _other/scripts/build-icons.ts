/**
 * Vendor the Iconify icons this repository actually references.
 *
 * Scans the repo for `prefix:name` icon references, fetches those icons from
 * the Iconify API, and writes one SVG sprite. The sprite is committed, so the
 * running site needs no CDN and no network.
 *
 * Run it after adding an icon name that is not already in the sprite:
 *
 *     deno task icons
 */

import { config } from "./config.ts";
import { errorMessage, fail, info, muted, ok, warn } from "./style.ts";

/** Only these Iconify collections are recognised, to keep matching tight. */
const PREFIXES = [
  "lucide",
  "mdi",
  "solar",
  "material-symbols",
  "ph",
  "tabler",
  "simple-icons",
  "carbon",
  // Longest first: the pattern alternates, and "thesvg" would otherwise be
  // tried against "thesvg-color:meta" and reject it.
  "thesvg-color",
  "thesvg",
];

const SCAN_EXTENSIONS = [".yaml", ".yml", ".html", ".js", ".ts", ".css", ".json", ".md"];
const SKIP_DIRECTORIES = [".git", "node_modules", "_other/git", ".vt"];
const API = "https://api.iconify.design";

/**
 * Matches both spellings of a reference: `lucide:house` as written in YAML and
 * JavaScript, and `lucide--house` as written in the sprite and in `<use href>`.
 */
const ICON_PATTERN = new RegExp(
  `\\b(${PREFIXES.join("|")})(?::|--)([a-z0-9][a-z0-9-]*)\\b`,
  "g",
);

const output = new URL(config.iconSprite, `file://${config.root}`);

async function* walk(directory: URL, relative = ""): AsyncGenerator<[URL, string]> {
  for await (const entry of Deno.readDir(directory)) {
    const path = `${relative}${entry.name}`;
    if (SKIP_DIRECTORIES.some((skip) => path === skip || path.startsWith(`${skip}/`))) {
      continue;
    }
    if (entry.isDirectory) {
      yield* walk(new URL(`${entry.name}/`, directory), `${path}/`);
    } else if (entry.isFile && SCAN_EXTENSIONS.some((ext) => entry.name.endsWith(ext))) {
      yield [new URL(entry.name, directory), path];
    }
  }
}

async function collectIconNames(): Promise<Map<string, Set<string>>> {
  const byPrefix = new Map<string, Set<string>>();
  const spritePath = config.iconSprite;

  for await (const [url, path] of walk(new URL(`file://${config.root}`))) {
    if (path === spritePath) continue;
    const text = await Deno.readTextFile(url);
    for (const [, prefix, name] of text.matchAll(ICON_PATTERN)) {
      const names = byPrefix.get(prefix!) ?? new Set<string>();
      names.add(name!);
      byPrefix.set(prefix!, names);
    }
  }
  return byPrefix;
}

interface IconifyResponse {
  width?: number;
  height?: number;
  icons?: Record<string, { body: string; width?: number; height?: number }>;
  not_found?: string[];
}

async function fetchCollection(prefix: string, names: string[]): Promise<string[]> {
  const response = await fetch(`${API}/${prefix}.json?icons=${names.sort().join(",")}`);
  if (!response.ok) {
    throw new Error(`${prefix} returned ${response.status} ${response.statusText}`);
  }
  const data = await response.json() as IconifyResponse;
  for (const missing of data.not_found ?? []) {
    warn(`no such icon: ${prefix}:${missing}`);
  }

  const symbols: string[] = [];
  for (const [name, icon] of Object.entries(data.icons ?? {})) {
    const width = icon.width ?? data.width ?? 24;
    const height = icon.height ?? data.height ?? 24;
    symbols.push(
      `  <symbol id="${prefix}--${name}" viewBox="0 0 ${width} ${height}">${icon.body}</symbol>`,
    );
  }
  return symbols;
}

const byPrefix = await collectIconNames();
const total = [...byPrefix.values()].reduce((sum, names) => sum + names.size, 0);
if (total === 0) fail("no icon references found");

info(
  `found ${total} icon${total === 1 ? "" : "s"} across ${byPrefix.size} collection${
    byPrefix.size === 1 ? "" : "s"
  } ${muted([...byPrefix.keys()].sort().join(", "))}`,
);

const symbols: string[] = [];
for (const [prefix, names] of [...byPrefix.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  try {
    symbols.push(...await fetchCollection(prefix, [...names]));
  } catch (error) {
    fail(`could not fetch ${prefix}: ${errorMessage(error)}`);
  }
}

const sprite = [
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">`,
  `  <!-- Generated by \`deno task icons\`. Edit the icon names in the repo, not this file. -->`,
  ...symbols,
  `</svg>`,
  "",
].join("\n");

await Deno.mkdir(new URL("./", output), { recursive: true });
await Deno.writeTextFile(output, sprite);
ok(`wrote ${symbols.length} symbols to ${config.iconSprite} ${muted(`(${sprite.length} bytes)`)}`);
